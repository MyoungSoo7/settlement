--
-- [왜 필요한가 — 화면이 비는 문제가 아니다]
--   insurance-service 에는 상품을 등록하는 API 도 유스케이스도 없다. 있는 것은 조회(상품설명서
--   교부)뿐이라, insurance_products 에 행을 넣을 수 있는 경로가 애플리케이션에 존재하지 않는다.
--   즉 마이그레이션 시드가 유일한 투입 경로인데 그게 없어서 상품 0행으로 뜬다.
--
--   상품이 0행이면 가입설계(CreateProposalQuoteService → LoadInsuranceProductPort)가 시작부터
--   막히고, 설계가 없으면 청약·계약·수수료까지 전 체인이 성립하지 않는다. 빈 화면이 아니라
--   도메인 전체가 실행 불가다.
--
--   요율(premium_rate_tables)도 함께 넣는다. PremiumRater 는 요율이 없으면 RateNotFoundException
--   을 던지고 임의 기본값으로 메꾸지 않는다(그게 정책이다) — 상품만 넣고 요율을 빼면 설계는
--   여전히 불가능하다. 시드를 절반만 채우는 실패를 피한다.
--
-- [이 값들의 성격] 실제 판매 상품이 아니라 도메인을 돌리기 위한 대표 카탈로그다. 수수료율·요율은
--   업계 공개 자료의 통상 범위를 참고한 대표값이며, 실제 인가 상품의 요율표가 아니다.
--   실 상품을 붙일 때는 이 시드를 지우지 말고 active=FALSE 로 내리면 된다 — 이미 이 상품으로
--   만들어진 설계·계약이 상품을 참조하고 있고, 판매종료 상품은 조회에서 404 로 은닉된다.
--
-- 멱등: 상품은 product_code, 요율은 uq_rate_band(product_code, gender, age_from, payment_term_years,
