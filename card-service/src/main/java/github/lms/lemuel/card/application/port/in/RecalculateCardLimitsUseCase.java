package github.lms.lemuel.card.application.port.in;

/**
 * 일 1회 마스터 한도 재산정 유스케이스.
 *
 * <p>카드 한도의 재원은 정산 잔액이라 <b>매일 움직인다</b>. 개설 시점 한도를 그대로 두면 재원이
 * 빠진 셀러에게 과거 근거로 만든 여신이 남는다 — 이 배치가 그 간극을 닫는 유일한 경로다.
 *
 * <p>입력이 없는 이유는 대상이 "지금 ACTIVE 인 카드계정 전부"로 이미 결정돼 있기 때문이다.
 * 반환값은 <b>실제로 바뀐 건수</b>다(조회 건수가 아니다) — 조용한 날에 0 이 나오는 것이 정상이고,
 * 그래야 로그·감사에서 "오늘 무엇이 움직였나"가 그대로 읽힌다.
 */
public interface RecalculateCardLimitsUseCase {

    /**
     * ACTIVE 카드계정 전체를 재심사한다. <b>한 계정의 실패가 배치를 중단시키지 않는다</b> —
     * 재원 조회는 account-service 로 나가는 외부 호출이라 일부 실패가 정상 범주이고, 거기서
     * 멈추면 뒤 계정들은 오늘치 재산정을 통째로 건너뛴 채 옛 한도로 남는다.
     *
     * @return 마스터 한도 또는 계정 상태가 실제로 바뀐 계정 수
     */
    int recalculateAll();
}
